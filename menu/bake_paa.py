#!/usr/bin/env python3
"""Crop the --bake screenshots into overlay textures and emit the layout include.

Inputs : out/bake_*.png + out/layout.json   (node render.mjs --bake)
Outputs: ../radio/addon/armapunk_menu/ui/*.paa   (25 textures, DXT5)
         ../radio/addon/armapunk_menu/layout.hpp (generated, committed)

Row strips are 1024x128 design-px centered on each 62px row (glow padding);
hints are 1024x64 anchored to the measured hint rect. Power-of-two as PAA
requires. Coordinates all come from layout.json — nothing hand-copied.
"""
import json
import os
import sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, 'tools'))
from make_paa import build_paa_dxt5, verify_paa  # noqa: E402

OUT = os.path.join(HERE, 'out')
ADDON = os.path.join(REPO, 'radio', 'addon', 'armapunk_menu')
UI = os.path.join(ADDON, 'ui')
ROW_W, ROW_H = 1024, 128
HINT_W, HINT_H = 1024, 64
ROW_X0 = 100          # 40px left of the row rect for bar glow
HIT_W = 520           # hover/click region: label width + selected offset + '<<'

layout = json.load(open(os.path.join(OUT, 'layout.json')))
rows = layout['rows']
hint = layout['hint']
assert len(rows) == 3 and all(round(r['h']) == 62 for r in rows), rows

os.makedirs(UI, exist_ok=True)
os.makedirs(os.path.join(OUT, 'paa_src'), exist_ok=True)

row_boxes, jobs = [], []
for i, r in enumerate(rows):
    yc = round(r['y'] + r['h'] / 2)
    box = (ROW_X0, yc - ROW_H // 2, ROW_X0 + ROW_W, yc + ROW_H // 2)
    row_boxes.append((box[0], box[1], ROW_W, ROW_H))
    jobs += [(f'bake_menu_dim.png', box, f'row_{i}_dim'),
             (f'bake_menu_sel_{i}.png', box, f'row_{i}_sel'),
             (f'bake_menu_pulse_{i}.png', box, f'row_{i}_pulse')]

hx0 = int(hint['x']) - 24
hbox = (hx0, 1080 - HINT_H, hx0 + HINT_W, 1080)
assert hint['x'] + hint['w'] <= hbox[2], (hint, hbox)
for k in range(3):
    jobs.append((f'bake_hint_{k}.png', hbox, f'hint_{k}'))
jobs.append(('bake_hint_armed.png', hbox, 'hint_armed'))

for src, box, name in jobs:
    im = Image.open(os.path.join(OUT, src)).convert('RGBA').crop(box)
    a_min, a_max = im.getextrema()[3]
    assert a_max > 0, f'{name}: fully transparent crop'
    png = os.path.join(OUT, 'paa_src', name + '.png')
    im.save(png)
    paa = os.path.join(UI, name + '.paa')
    build_paa_dxt5(png, paa)
    ok, info = verify_paa(paa)
    assert ok, f'{name}: {info}'
print(f'{len(jobs)} PAAs -> {UI}')

hpp = os.path.join(ADDON, 'layout.hpp')
fmt = lambda b: '[%d,%d,%d,%d]' % b
with open(hpp, 'w') as f:
    f.write('// GENERATED by menu/bake_paa.py from measured design layout — do not hand-edit\n')
    f.write('#define AP35_CANVAS_H 1080\n')
    f.write('#define AP35_CANVAS_169_W 1920\n#define AP35_CANVAS_219_W 2580\n')
    f.write('#define AP35_ROW_BOXES [%s]\n' % ','.join(fmt(b) for b in row_boxes))
    f.write('#define AP35_ROW_HITS [%s]\n' % ','.join(
        fmt((round(r['x']), round(r['y']), HIT_W, round(r['h']))) for r in rows))
    f.write('#define AP35_HINT_BOX %s\n' % fmt((hbox[0], hbox[1], HINT_W, HINT_H)))
print('wrote', hpp)
