#!/usr/bin/env python3
"""holo-manifest.json ticker_path -> custom_p3ds/lux_ticker_data.sqf

The crown ticker is the one hologram feature that runs WITHOUT an addon
(handoff's own recommendation): a client-side drawIcon3D marching text over
49 path points around the crown band. The manifest points are in p3d frame
(x, y_up, z_north); the spawner feeds them to modelToWorldVisual, whose frame
is the autocentered bbox — so convert with the same constants as the doors:
model = [p3d_x, p3d_z - ZC, p3d_y - YC].
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, '..', 'scratchpad', 'skyscraper', 'holo-manifest.json')
OUT = os.path.join(HERE, '..', 'mission', 'Armapunk2035.Malden',
                   'custom_p3ds', 'lux_ticker_data.sqf')
ZC, YC = 1.845, 58.460          # skyscraper30_r12 autocenter offsets (build print, unchanged r3->r4)

pts = json.load(open(MANIFEST))['ticker_path']
assert len(pts) == 49, len(pts)
assert [p['name'] for p in pts] == [f'ticker_path_{i:02d}' for i in range(49)]

rows = []
for p in pts:
    x, y, z = p['pos']
    rows.append(f'[{x:.3f},{z - ZC:.3f},{y - YC:.3f}]')

with open(OUT, 'w') as f:
    f.write('// GENERATED by tools/gen_lux_ticker.py from holo-manifest.json '
            f'(skyscraper30_r12, ZC {ZC} YC {YC}) -- do not hand-edit\n')
    f.write('[\n    ' + ',\n    '.join(rows) + '\n]\n')
print(f'wrote {OUT} ({len(rows)} points)')
