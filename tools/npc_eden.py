#!/usr/bin/env python3
"""
npc_eden.py -- drag the shop NPCs around in 3DEN instead of typing coordinates.

    python3 tools/npc_eden.py stage     # write the edenNPC_*.sqf helpers into the mission
    python3 tools/npc_eden.py apply     # read the editor's export back into fn_mapData.sqf
    python3 tools/npc_eden.py apply -n  # show what would change, write nothing

WHY THE NPCs ARE NOT IN THE EDITOR ALREADY, and why this is not a bug to fix. A shop NPC has to be a
client-local `allLocalMapEntities` row -- the trailing `false` -- so every player instantiates their
own copy and a scroll-wheel addAction works on it. An Eden-placed unit is a single server-owned AI
that sells nothing. So the NPCs genuinely cannot live in mission.sqm, and 3DEN has nothing to show.

What this does instead is the same trick tools/eden_edit.py uses for the custom .p3d buildings: put a
draggable ANCHOR in the editor for each NPC, draw the right character model next to it so you can see
who it is, let you move the anchors, then read the anchors back out and rewrite the mapData rows.

    anchor  = Land_HelipadEmpty_F, a real 3DEN entity -- drags, snaps, undoes like anything else
    visual  = createSimpleObject of the unit's model -- NOT an entity, so 3DEN will not save it

FRAME, and this is the one that bites. mapData positions are applied with setPosATL, so this reads and
writes getPosATL -- above *terrain*. eden_edit.py deliberately uses getPosWorld instead, because
createSimpleObject places buildings by their model centre. The two tools are not interchangeable;
using the building frame here would sink or float every NPC by whatever the model offset happens
to be.

HEADING is degrees clockwise from north; the row stores it as vectorDir [sin(h), cos(h), 0]. That
conversion is imported from npc_move.py rather than repeated, because a second copy that drifts
silently encodes (180 - h) and turns every NPC around.
"""
import argparse
import glob
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import npc_move  # ROW parsing, the vectorDir convention, and the lh_* marker mover

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MISSION = os.path.join(REPO, "mission", "Armapunk2035.Malden")
MAPDATA = npc_move.MAP
RPT_DIR = os.path.expanduser(
    "~/.local/share/Steam/steamapps/compatdata/107410/pfx/drive_c/users/steamuser/"
    "AppData/Local/Arma 3")

BANNER = "// GENERATED by tools/npc_eden.py -- do not hand-edit, re-run `stage` instead.\n\n"


def rows():
    src = open(MAPDATA, encoding="utf-8", errors="surrogateescape").read()
    return src, npc_move.npcs(src)


def do_stage():
    src, ns = rows()
    if not ns:
        print("no NPC rows found in", os.path.relpath(MAPDATA, REPO))
        return 1

    data = [BANNER, "AP_npcData = [\n"]
    rows = ['    [%d, "%s", [%.3f, %.3f, %.3f], %.2f, "%s"]'
            % (i, r["cls"], r["x"], r["y"], r["z"],
               npc_move.bearing(r["dx"], r["dy"]), r["tag"]) for i, r in enumerate(ns)]
    # SQF rejects a trailing comma in array literals — the original emitter
    # put one after every row and the whole file silently failed to compile
    data.append(",\n".join(rows))
    data.append("\n];\n")
    open(os.path.join(MISSION, "edenNPC_data.sqf"), "w", encoding="utf-8").write("".join(data))

    open(os.path.join(MISSION, "edenNPC_import.sqf"), "w", encoding="utf-8").write(BANNER + r'''
// Put an anchor in the editor for every shop NPC, with the character model drawn on it.
// Run in the 3DEN debug console:  call compile preprocessFileLineNumbers "edenNPC_import.sqf";
call compile preprocessFileLineNumbers "edenNPC_data.sqf";
if (!isNil "AP_npcVis") then { { deleteVehicle _x } forEach AP_npcVis; };
AP_npcVis = []; AP_npcAnchors = [];
{
    _x params ["_idx", "_cls", "_pos", "_dir", "_tag"];
    // the anchor: a real 3DEN entity, so it drags, snaps and survives undo
    private _a = create3DENEntity ["Object", "Land_HelipadEmpty_F", _pos];
    _a setPosATL _pos;                        // ATL -- the frame the mapData row is applied in
    _a setDir _dir;
    _a set3DENAttribute ["name", format ["npc%1_%2", _idx, _tag]];
    _a setVariable ["AP_npcIdx", _idx];
    AP_npcAnchors pushBack _a;
    // the visual: a plain simple object, NOT an entity -- 3DEN will not save or bake it
    private _m = getText (configFile >> "CfgVehicles" >> _cls >> "model");
    if (_m != "") then {
        if (toLower (_m select [(count _m) - 4]) != ".p3d") then { _m = _m + ".p3d"; };
        private _v = createSimpleObject [_m, [0,0,0], true];
        _v setPosATL _pos; _v setDir _dir;
        AP_npcVis pushBack _v;
    };
} forEach AP_npcData;
systemChat format ["edenNPC: %1 anchors placed. Move them, then run edenNPC_export.sqf.", count AP_npcAnchors];
''')

    open(os.path.join(MISSION, "edenNPC_refresh.sqf"), "w", encoding="utf-8").write(BANNER + r'''
// Snap the character models back onto the anchors after you have moved them.
// Run in the 3DEN debug console:  call compile preprocessFileLineNumbers "edenNPC_refresh.sqf";
if (isNil "AP_npcAnchors") exitWith { systemChat "edenNPC: run edenNPC_import.sqf first"; };
{ deleteVehicle _x } forEach AP_npcVis;
AP_npcVis = [];
call compile preprocessFileLineNumbers "edenNPC_data.sqf";
{
    private _idx = _x getVariable ["AP_npcIdx", -1];
    private _cls = ((AP_npcData select { (_x select 0) == _idx }) param [0, ["", "", [0,0,0], 0, ""]]) select 1;
    private _m = getText (configFile >> "CfgVehicles" >> _cls >> "model");
    if (_m != "") then {
        if (toLower (_m select [(count _m) - 4]) != ".p3d") then { _m = _m + ".p3d"; };
        private _v = createSimpleObject [_m, [0,0,0], true];
        _v setPosATL (getPosATL _x); _v setDir (getDir _x);
        AP_npcVis pushBack _v;
    };
} forEach (AP_npcAnchors select { !isNull _x });
systemChat "edenNPC: models redrawn on the anchors.";
''')

    open(os.path.join(MISSION, "edenNPC_export.sqf"), "w", encoding="utf-8").write(BANNER + r'''
// Write the anchors back out. Run in the 3DEN debug console:
//     call compile preprocessFileLineNumbers "edenNPC_export.sqf";
// then, in a terminal:  python3 tools/npc_eden.py apply
if (isNil "AP_npcAnchors") exitWith { systemChat "edenNPC: run edenNPC_import.sqf first"; };
private _n = 0;
{
    if (!isNull _x) then {
        private _p = getPosATL _x;            // ATL: the frame fn_createVehicleLocal applies
        diag_log format ["-NPCEXPORT- %1|%2|%3|%4|%5",
            _x getVariable ["AP_npcIdx", -1],
            (_p select 0) toFixed 3, (_p select 1) toFixed 3, (_p select 2) toFixed 3,
            (getDir _x) toFixed 2];
        _n = _n + 1;
    };
} forEach AP_npcAnchors;
diag_log format ["-NPCEXPORT- END %1", _n];
systemChat format ["edenNPC: %1 exported. Now run: python3 tools/npc_eden.py apply", _n];
''')

    print("staged into", os.path.relpath(MISSION, REPO) + ":")
    for f in ("edenNPC_data.sqf", "edenNPC_import.sqf", "edenNPC_refresh.sqf", "edenNPC_export.sqf"):
        print("   ", f)
    print(f"\n{len(ns)} NPCs staged.\n")
    # Every line below is valid SQF -- commands are ";"-terminated, commentary is "//" -- so pasting
    # the whole block is safe. An unterminated command swallows whatever follows it and reports
    # "Missing ;" against the wrong file (67dc326b).
    print("In 3DEN, paste ONE line at a time or the whole block -- both are safe:\n")
    print('    call compile preprocessFileLineNumbers "edenNPC_import.sqf";')
    print("    // ... now drag the anchors in the editor ...")
    print('    call compile preprocessFileLineNumbers "edenNPC_refresh.sqf";   // redraw the models')
    print('    call compile preprocessFileLineNumbers "edenNPC_export.sqf";')
    print("\nThen:  python3 tools/npc_eden.py apply")
    print("\nDo NOT save the mission from 3DEN -- the anchors would be baked into mission.sqm.")
    return 0


def exported():
    """Newest complete -NPCEXPORT- block from the client RPT."""
    rpts = sorted(glob.glob(os.path.join(RPT_DIR, "*.rpt")), key=os.path.getmtime)
    if not rpts:
        return None, "no client RPT found"
    got, saw_end = {}, False
    for line in open(rpts[-1], encoding="utf-8", errors="replace"):
        if "-NPCEXPORT- END" in line:
            saw_end = True
            continue
        m = re.search(r"-NPCEXPORT- (-?\d+)\|([-\d.]+)\|([-\d.]+)\|([-\d.]+)\|([-\d.]+)", line)
        if m:
            if saw_end:                        # a newer run started: drop the older block
                got, saw_end = {}, False
            got[int(m.group(1))] = tuple(float(v) for v in m.groups()[1:])
    if not got:
        return None, "no -NPCEXPORT- lines in " + os.path.basename(rpts[-1])
    return got, None


def do_apply(dry):
    got, err = exported()
    if err:
        print(err)
        print("In 3DEN: call compile preprocessFileLineNumbers \"edenNPC_export.sqf\";")
        return 1
    src, ns = rows()
    bad = [i for i in got if i < 0 or i >= len(ns)]
    if bad:
        print(f"REFUSING: export names row index {bad[:5]}, but the source has {len(ns)} rows.")
        print("The mapData rows changed since `stage` -- re-run `stage` and re-import in 3DEN.")
        return 2

    changed = []
    for i, (x, y, z, d) in sorted(got.items()):
        r = ns[i]
        if (abs(r["x"] - x) > 0.005 or abs(r["y"] - y) > 0.005 or abs(r["z"] - z) > 0.005
                or abs(npc_move.bearing(r["dx"], r["dy"]) - d) > 0.05):
            changed.append((i, r, (x, y, z, d)))
    print(f"{len(changed)} of {len(ns)} NPCs moved.")
    for i, r, (x, y, z, d) in changed:
        print(f"  #{i:3d} {r['tag']:22s} [{r['x']:8.2f},{r['y']:8.2f},{r['z']:6.2f}] "
              f"brg {npc_move.bearing(r['dx'], r['dy']):5.0f}  ->  [{x:8.2f},{y:8.2f},{z:6.2f}] brg {d:5.0f}")
    if not changed or dry:
        print("(nothing written)" if dry else "")
        return 0

    out = src
    for i, r, (x, y, z, d) in sorted(changed, key=lambda t: -t[1]["m"].start()):  # back to front
        dx, dy = npc_move.vecdir(d)
        line = ('["%s",[%.3f,%.3f,%.3f],[[%.4f,%.4f,0.0000],[0.0000,0.0000,1.0000]],"%s",false]'
                % (r["cls"], x, y, z, dx, dy, r["init"].replace('"', '""')))
        m = r["m"]
        out = out[:m.start()] + line + out[m.end():]
    shutil.copy(MAPDATA, MAPDATA + ".bak-eden")
    open(MAPDATA, "w", encoding="utf-8", errors="surrogateescape").write(out)

    after = npc_move.npcs(open(MAPDATA, encoding="utf-8", errors="surrogateescape").read())
    print(f"\nwritten. rows still parse: {len(after)} (was {len(ns)})")
    if len(after) != len(ns):
        print("ROW COUNT CHANGED -- restore from", os.path.basename(MAPDATA) + ".bak-eden")
        return 3
    # a shop's map label should follow its NPC, same as npc_move does for a single move
    moved = 0
    for i, r, (x, y, z, d) in changed:
        if npc_move.move_marker(r["x"], r["y"], x, y, z, 60.0):
            moved += 1
    print(f"markers followed: {moved}")
    print("deploy:  bash /home/timb/arma3server_dev/reload-armapunk2035.sh")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("stage", "apply"))
    ap.add_argument("-n", "--dry-run", action="store_true")
    a = ap.parse_args()
    return do_stage() if a.cmd == "stage" else do_apply(a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
