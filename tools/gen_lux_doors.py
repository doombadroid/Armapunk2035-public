#!/usr/bin/env python3
"""doors-manifest.json -> custom_p3ds/skyscraper_doors_data.sqf

Emits one entry per door for the no-addon leaf spawner:
    [hingeModelPos, yawAddDeg, kindIdx, openAngleDeg]

hingeModelPos is in the BUILDING's script model frame (modelToWorld input:
[x, depth, up]); the manifest is authored in p3d frame (x, y_up, z_north), and
the r12 build's autocentered bbox is x +-12.03, y 0..77.19, z -12.03..14.80,
so: model = [p3d_x, p3d_z - 1.385, p3d_y - 38.595].

yawAddDeg rotates the leaf (local +X = span direction away from the hinge)
relative to the building's facing. kindIdx: 0 = door_leaf_wide (span 1.065),
1 = door_leaf_narrow (span 0.965). openAngleDeg keeps the manifest's sign
(matches setDir's positive direction — proven by the r6..r11 static bakes).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import door_park
MANIFEST = os.path.join(HERE, '..', 'scratchpad', 'skyscraper', 'lux-doors-manifest.json')
OUT = os.path.join(HERE, '..', 'mission', 'Armapunk2035.Malden',
                   'custom_p3ds', 'lux_doors_data.sqf')
ZC, YC = 1.845, 58.460          # r3 autocenter (v11 foundation shifts YC -1.5)

doors = json.load(open(MANIFEST))['doors']
assert len(doors) == 88, len(doors)

# b0346: owner call — every door swings the OTHER way from the manifest, and
# parks as flat as its surroundings allow (measured per door against the
# tower's Geometry LOD; the manifest's 100 deg leaves it ajar in the walk path)
TOWER = door_park.newest(os.path.join(HERE, '..', 'mission', 'Armapunk2035.Malden',
                                      'skyscraper30_r*.p3d'))
PARK = door_park.park_angles(doors, TOWER, sign=-1)

rows = []
kinds = {0: 0, 1: 0, 2: 0}
for d in sorted(doors, key=lambda q: int(q['id'].split('_')[1])):
    b = d['box']
    ax, az, y0 = d['axis']['x'], d['axis']['z'], b[2]
    along_x = (b[1] - b[0]) > (b[5] - b[4])
    span = (b[1] - b[0]) if along_x else (b[5] - b[4])
    if along_x:
        yaw = 0.0 if abs(b[0] - ax) < abs(b[1] - ax) else 180.0
    else:
        # leaf +X must map onto the building z axis: +X->+Z is -90 (setDir
        # sign convention measured against the r6 bake), +X->-Z is +90
        far_plus_z = abs(b[5] - az) > abs(b[4] - az)
        yaw = -90.0 if far_plus_z else 90.0
    kind = 0 if span > 1.0 else (1 if span > 0.93 else 2)
    kinds[kind] += 1
    hinge = [round(ax, 4), round(az - ZC, 4), round(y0 - YC, 4)]
    ang = PARK[d['id']]
    rows.append(f'    [[{hinge[0]},{hinge[1]},{hinge[2]}], {yaw:g}, {kind}, {ang:g}]')

with open(OUT, 'w') as f:
    f.write('// GENERATED by tools/gen_skyscraper_doors.py from doors-manifest.json — do not hand-edit.\n')
    f.write('// [hingeModelPos(modelToWorld frame), yawAddDeg, kind(0=wide,1=narrow), openAngleDeg]\n')
    f.write('[\n' + ',\n'.join(rows) + '\n]\n')
import collections as _c
print(f'wrote {os.path.normpath(OUT)}: {len(rows)} doors, k106={kinds[0]} k94={kinds[1]} k92={kinds[2]}')
print(f'  park angles (measured vs {os.path.basename(TOWER)}): '
      f'{dict(_c.Counter(PARK.values()))}')
