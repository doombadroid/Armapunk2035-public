#!/usr/bin/env python3
"""
gen_casino.py -- emit the LooneyBin casino dialogs (common button base + landing + coinflip + wheel + hilo)
as .hpp. Aspect-locked 2:1 phone coordinate system (positions are QUOTED runtime expressions:
safezoneX/pixelGrid resolve at dialog creation). Buttons inherit AP_CasinoBtn (type=1 style=2 => CENTERED
text, fixing the left-jammed RscButtonMenu look). Plain casino_felt.paa background (no card-table arc).
Run:  python3 gen_casino.py
"""
import os
OUT = os.path.join(os.path.dirname(__file__), "..", "mission", "Armapunk2035.Malden", "dialog")

# NB: coords must be emitted BARE (unquoted) so the config preprocessor expands the UI_GRID_* macros.
# Quoting them ("...UI_GRID_W...") leaves the macro literal -> Arma evals undefined var -> 0 -> invisible dialog.
def cx(v): return f'({round(-1.055 + v*36.09,4)})*UI_GRID_W + UI_GRID_X'   # mapped into the PAA screen rect x[-19.1..16.99]
def cy(v): return f'({round(1.05 + v*16.0,4)})*UI_GRID_H + UI_GRID_Y'      # content zone y[-6.95..9.05] (below the baked header divider)
def cw(v): return f'({round(v*36.09,4)})*UI_GRID_W'
def ch(v): return f'({round(v*16.0,4)})*UI_GRID_H'
def col(t): return "{" + ",".join(str(x) for x in t) + "}"

def background():
    return (
        '    class controlsBackground {\n'
        '        class Dim: AP_RscText { idc=-1; x=safezoneX; y=safezoneY; w=safezoneW; h=safezoneH; colorBackground[]={0,0,0,0.55}; };\n'
        '        class CasFelt: AP_RscPicture { idc=-1; '
        'x="safezoneX + 0.5*safezoneW + (-0.48818)*77.4*pixelGrid*pixelW"; '
        'y="safezoneY + 0.5*safezoneH + (-0.46228)*37.6*pixelGrid*pixelH"; '
        'w="(0.97547)*77.4*pixelGrid*pixelW"; h="(0.92457)*37.6*pixelGrid*pixelH"; '
        'colorText[]={1,1,1,1}; text="images\\casino\\casino_felt.paa"; };\n'
        '        class CasFrame: AP_RscPicture { idc=-1; '
        'x=-20*UI_GRID_W + UI_GRID_X; '
        'y=-10*UI_GRID_H + UI_GRID_Y; '
        'w=40*UI_GRID_W; h=20*UI_GRID_H; '
        'colorText[]={1,1,1,1}; text="images\\phone_deck_blank.paa"; };\n'
        '    };\n'
    )

def stext(cls, idc, x, y, w, h, text="", align="center", size=1.55, hidden=False, bg=None):
    parts = [f'class {cls}: AP_RscStructuredText {{ idc={idc};',
             f'x={cx(x)}; y={cy(y)}; w={cw(w)}; h={ch(h)};',
             f'class Attributes {{ align="{align}"; }};',
             f'size={round(size*16.0/37.6,4)}*UI_GRID_H; text="{text}";']
    if bg is not None: parts.append(f'colorBackground[]={col(bg)};')
    if hidden: parts.append('onLoad="(_this select 0) ctrlShow false";')
    parts.append('};')
    return "        " + " ".join(parts) + "\n"

def btn(cls, idc, x, y, w, h, text, bg=(0.06,0.11,0.09,1), bga=(0.16,0.24,0.12,1),
        tcol=(1,1,1,1), hidden=False, size=1.5):
    parts = [f'class {cls}: AP_CasinoBtn {{ idc={idc};',
             f'x={cx(x)}; y={cy(y)}; w={cw(w)}; h={ch(h)};',
             f'sizeEx={round(size*16.0/37.6,4)}*UI_GRID_H; text="{text}";',
             f'colorText[]={col(tcol)}; colorBackground[]={col(bg)}; colorBackgroundActive[]={col(bga)}; colorFocused[]={col(bga)};']
    if hidden: parts.append('onLoad="(_this select 0) ctrlShow false";')
    parts.append('};')
    return "        " + " ".join(parts) + "\n"

def pic_stretch(cls, idc, x, y, w, h, text="", hidden=True):
    """AP_RscPicture: STRETCHES image to the box (used for the coin so a width-squash reads as a flip)."""
    parts = [f'class {cls}: AP_RscPicture {{ idc={idc}; x={cx(x)}; y={cy(y)}; w={cw(w)}; h={ch(h)}; colorText[]={{1,1,1,1}}; text="{text}";']
    if hidden: parts.append('onLoad="(_this select 0) ctrlShow false";')
    parts.append('};')
    return "        " + " ".join(parts) + "\n"

def pic_aspect(cls, idc, x, y, w, h, hidden=True):
    parts = [f'class {cls}: AP_RscPictureKeepAspect {{ idc={idc};',
             f'x={cx(x)}; y={cy(y)}; w={cw(w)}; h={ch(h)}; colorBackground[]={{0,0,0,0}};']
    if hidden: parts.append('onLoad="(_this select 0) ctrlShow false";')
    parts.append('};')
    return "        " + " ".join(parts) + "\n"

def dialog(fname, idd, name, controls, on_unload=None, header=""):
    out = [f'/*\n    {fname}  (LooneyBin -- Casino, generated by scratchpad/gen_casino.py). idd {idd}.\n    {header}\n*/\n',
           f'class {name} {{\n',
           f'    idd = {idd};\n    name = "{name}";\n    movingEnable = false;\n    enableSimulation = true;\n']
    if on_unload: out.append(f'    onUnload = "{on_unload}";\n')
    out.append(background()); out.append('    class controls {\n'); out.append(controls); out.append('    };\n};\n')
    with open(os.path.join(OUT, fname), "w") as f: f.write("".join(out))
    print("wrote", fname)

