-- Armapunk Pixel v3 (PIXEL_SPEC.md § Data model). Portal-only state, no game-server tie-in.
--   docker exec -i armapunk-pg psql -U armapunk -d armapunk -v ON_ERROR_STOP=1 < website/sql/pg/web_pixel.sql
-- Re-runnable: every statement is IF NOT EXISTS, ON CONFLICT DO NOTHING or a grant. A v2 install
-- must run web_pixel_v3.sql first (it drops the v2 tables; the market column and the save changed).

-- One jsonb save per player (state.v = 3) plus the columns the roster, leaderboard, feed and
-- dispatch read without parsing the save. faction is NULL until the career picker.
CREATE TABLE IF NOT EXISTS web_pixel_players (
  steamid      varchar(17) NOT NULL,
  name         varchar(64) NOT NULL DEFAULT '',
  avatar_url   text NOT NULL DEFAULT '',
  state        jsonb NOT NULL,
  faction      text NULL,
  city         text NOT NULL DEFAULT 'kavala',
  level        integer NOT NULL DEFAULT 1,
  prestige     integer NOT NULL DEFAULT 0,
  net_worth    bigint NOT NULL DEFAULT 0,
  gang_id      text NULL,
  heat         double precision NOT NULL DEFAULT 0,
  wanted       boolean NOT NULL DEFAULT false,
  jailed_until timestamptz NULL,
  travelling   boolean NOT NULL DEFAULT false,
  last_seen    timestamptz NOT NULL DEFAULT now(),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_pixel_players_pkey PRIMARY KEY (steamid)
);
CREATE INDEX IF NOT EXISTS web_pixel_players_net_worth ON web_pixel_players (net_worth DESC);
CREATE INDEX IF NOT EXISTS web_pixel_players_last_seen ON web_pixel_players (last_seen DESC);

-- Shared per-city price multipliers (fall with every sale, recover toward the resting value).
CREATE TABLE IF NOT EXISTS web_pixel_market (
  city       text NOT NULL,
  item       text NOT NULL,
  mult       double precision NOT NULL DEFAULT 1.18,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_pixel_market_pkey PRIMARY KEY (city, item)
);

-- Append-only feed: kinds bust / raid / sale / jackpot / join / level; the snapshot shows the newest 40.
CREATE TABLE IF NOT EXISTS web_pixel_events (
  id      bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  steamid varchar(17) NOT NULL,
  at      timestamptz NOT NULL DEFAULT now(),
  kind    text NOT NULL,
  text    text NOT NULL,
  CONSTRAINT web_pixel_events_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS web_pixel_events_id ON web_pixel_events (id DESC);

-- Chat: the newest 200 rows are retained; pruning bumps chat_revision so clients refetch the window.
CREATE TABLE IF NOT EXISTS web_pixel_chat (
  id      bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  at      timestamptz NOT NULL DEFAULT now(),
  steamid varchar(17) NOT NULL,
  name    varchar(64) NOT NULL,
  faction text NULL,
  text    varchar(240) NOT NULL,
  CONSTRAINT web_pixel_chat_pkey PRIMARY KEY (id)
);

-- Gangs: the engine's GangRecord as jsonb (members inside) plus the columns the directory sorts on.
CREATE TABLE IF NOT EXISTS web_pixel_gangs (
  id             text NOT NULL,
  name           varchar(20) NOT NULL,
  tag            varchar(4) NOT NULL,
  leader_steamid varchar(17) NOT NULL,
  record         jsonb NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_pixel_gangs_pkey PRIMARY KEY (id)
);

-- Per-city "Reported criminal activity" (0..100), consumed by paid dispatch calls, regenerating per minute.
CREATE TABLE IF NOT EXISTS web_pixel_npc_crime (
  city       text NOT NULL,
  value      double precision NOT NULL DEFAULT 100,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_pixel_npc_crime_pkey PRIMARY KEY (city)
);

-- The one shared casino table (Live Poker Showdown) as jsonb.
CREATE TABLE IF NOT EXISTS web_pixel_casino (
  id         text NOT NULL,
  state      jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_pixel_casino_pkey PRIMARY KEY (id)
);

-- Chat cursor: generation (a uuid per install) and revision (bumped on prune).
CREATE TABLE IF NOT EXISTS web_pixel_meta (
  key   text NOT NULL,
  value text NOT NULL,
  CONSTRAINT web_pixel_meta_pkey PRIMARY KEY (key)
);
INSERT INTO web_pixel_meta (key, value) VALUES ('chat_generation', gen_random_uuid()::text), ('chat_revision', '1') ON CONFLICT (key) DO NOTHING;

-- The portal connects as armapunk_web; role_web.sql only grants on tables that existed when it ran.
GRANT SELECT, INSERT, UPDATE, DELETE ON web_pixel_players, web_pixel_market, web_pixel_events, web_pixel_chat, web_pixel_gangs,
  web_pixel_npc_crime, web_pixel_casino, web_pixel_meta TO armapunk_web;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE web_pixel_events_id_seq, web_pixel_chat_id_seq TO armapunk_web;
